-- ---------------------------------------------------------------------------
-- 0041 - outbox_event, the transactional outbox, and the kasuwa_relay grants
-- (T-0098, Agent 1; ADR-0018 as amended by D-L156; D-L128 Q1-Q5, D-P29,
-- D-P30 item 2, D-L146). D-A3: a new table, RLS, and grants to a new role ->
-- @acexode.
--
-- CLAUDE.md 2.6 says events go through an outbox and 2.5 says no domain calls
-- another. This is that outbox: a producer appends a row inside its own
-- withTenantTransaction (appendOutboxEvent, @kasuwa/db), so the event commits
-- with the change or not at all; apps/worker's relay drains it into BullMQ.
--
-- In this one file: the role assertion; locks; the table, its checks, keys and
-- indexes; RLS, policies and grants; a self-check of the posture.
-- One transaction: a failure anywhere leaves no trace, not even a ledger row.
--
-- ---------------------------------------------------------------------------
-- THE ROLE (asserted first, before anything is created)
-- ---------------------------------------------------------------------------
-- kasuwa_relay is created by sql/bootstrap.sql, which runs outside this
-- runner, so it is ASSERTED here, as 0020 and 0024 do for their roles. The
-- file stops, naming the role, if it is missing, or if it is:
--   - anything but LOGIN, NOBYPASSRLS, NOSUPERUSER, NOCREATEDB, NOCREATEROLE,
--     NOREPLICATION;
--   - a member of any role, or has any member (kasuwa_app above all: the
--     relay must never be reachable by SET ROLE from an app connection,
--     ADR-0013's reasoning);
--   - the owner of anything, or named by a default privilege;
--   - holding any privilege on any relation or sequence, USAGE on any schema
--     but public, CREATE anywhere, TEMPORARY on the database, or a function
--     grant naming it.
-- That is "nothing beyond this plan is held" BEFORE the plan is applied. The
-- self-check at the end proves the plan landed, and nothing more.
--
-- ---------------------------------------------------------------------------
-- COLUMNS (ADR-0018 point 1; the T-0098 suite I3)
-- ---------------------------------------------------------------------------
--   id               uuid PK, generated by the producer: the BullMQ jobId and
--                    the consumer's idempotency key.
--   seq              bigint GENERATED ALWAYS AS IDENTITY: the claim order.
--                    kasuwa_app holds no INSERT on it (D-L156), so OVERRIDING
--                    SYSTEM VALUE cannot reorder an aggregate.
--   tenant_id        uuid NOT NULL.
--   programme_id     uuid NOT NULL (Q1: no tenant-level events yet).
--   actor_user_id    uuid NOT NULL (Q2: system jobs act as their initiator).
--                    The consumer re-enters the tenant AS this user.
--   event_type       text, a dotted lower-case code ('contact.owner_changed').
--   schema_version   smallint >= 1.
--   aggregate_type   text, a lower-case code ('contact').
--   aggregate_id     uuid.
--   payload          jsonb object: identifiers, codes and timestamps only
--                    (D-P29). The strict per-type Zod schema in @kasuwa/db is
--                    the content rule; the relay re-parses it before enqueue
--                    (R3). The CHECKs here bound shape and size only.
--   created_at       timestamptz NOT NULL DEFAULT now().
--   published_at     set by the relay to now() when the batch is enqueued.
--   attempts         smallint NOT NULL DEFAULT 0: failed publish attempts.
--   last_attempt_at  set with each failed attempt.
--   dead_at          set to now() at the 10th failed attempt (Q3).
--
-- ---------------------------------------------------------------------------
-- KEYS
-- ---------------------------------------------------------------------------
--   - tenant_id -> tenant (id): ON DELETE CASCADE (offboarding; also what
--     lets the seed's TRUNCATE tenant CASCADE clear the table).
--   - (tenant_id, programme_id) -> programme (tenant_id, id): ON DELETE
--     CASCADE. A row's programme is in its tenant.
--   - actor_user_id has NO foreign key, deliberately:
--       * the T-0098 tenancy suite plants, as the migrator, a row naming
--         another tenant's actor ("written past every app check") and pins
--         that the consumer drops it; a composite FK would make that row
--         impossible to write and the test unrunnable;
--       * an event is history: a user delete (D-L61, still open) must not be
--         blocked by the outbox's 7 to 30 days of rows.
--     What binds the actor instead: kasuwa_app can only insert
--     actor_user_id = app.current_user_id() (F-R3, the restrictive policy),
--     which is a user resolved in the session's tenant; and the consumer
--     re-resolves the actor with withTenantTransaction before it acts, so an
--     actor from another tenant or no longer active is dropped (point 8).
--   - aggregate_id has no FK: it names a row of any aggregate type.
--   Referential checks ignore row security, so the FKs that exist carry
--   tenant_id.
--
-- ---------------------------------------------------------------------------
-- RLS AND GRANTS (ADR-0018 points 3 and 4, amended by D-L156)
-- ---------------------------------------------------------------------------
--   ENABLED and FORCED; in TENANT_SCOPED_TABLES and the schema.ts mirror.
--
--   kasuwa_app:
--     - outbox_event_tenant, permissive FOR ALL TO kasuwa_app: tenant AND
--       programme, WITH CHECK identical to USING (CLAUDE.md 2.4). It has no
--       publish-state predicate, so the consumer can re-read a row the relay
--       has already published (point 8).
--     - outbox_event_insert_as_session, RESTRICTIVE FOR INSERT TO kasuwa_app:
--       actor_user_id = app.current_user_id() (F-R3, D-L156). Without it any
--       SQL inside a tenant could write an event naming the supervisor as the
--       actor, and the consumer would run as the supervisor, with the
--       supervisor's scope.
--     - SELECT, and INSERT on exactly (id, tenant_id, programme_id,
--       actor_user_id, event_type, schema_version, aggregate_type,
--       aggregate_id, payload). Never seq (D-L156), and never created_at or
--       the four publication columns, so the app cannot insert a row that is
--       already published, dead or back-dated. NO UPDATE and NO DELETE (the
--       0024 pattern): SQL inside a tenant cannot mark its own events
--       published or erase them. No TRUNCATE, REFERENCES or TRIGGER. Nothing
--       on the identity sequence.
--
--   kasuwa_relay (all three policies TO kasuwa_relay, so neither role ever
--   evaluates the other's predicate, and the relay needs no EXECUTE on the
--   app accessors and no USAGE on schema app):
--     - outbox_event_relay_select, FOR SELECT:
--         (published_at IS NULL AND dead_at IS NULL)      undispatched
--         OR published_at = now() OR dead_at = now()      marked in THIS txn
--         OR published_at < now() - '7 days'              past retention
--         OR dead_at      < now() - '30 days'             past retention
--       The middle line is D-L156's amendment. An UPDATE with a WHERE clause
--       needs SELECT rights, so PostgreSQL checks the NEW row against the
--       SELECT policy too, RETURNING or not; as ADR-0018 wrote it the relay
--       could not mark a row published or dead. now() is fixed per
--       transaction, so only rows marked in the current transaction pass; in
--       any later one a published or dead row is out of view again until it
--       is past retention.
--     - outbox_event_relay_update, FOR UPDATE:
--         USING      published_at IS NULL AND dead_at IS NULL
--         WITH CHECK (published_at IS NULL OR published_at = now())
--                    AND (dead_at IS NULL OR dead_at = now())
--                    AND (last_attempt_at IS NULL OR last_attempt_at <= now())
--       D-L156 tightened ADR-0018's `published_at <= now()`: nothing can be
--       back-dated into retention, where the DELETE policy would erase an
--       undispatched event, nor dated into the future. The last line is this
--       file's own tightening: the relay's publish backoff (outbox-relay.ts)
--       skips a row until last_attempt_at plus a delay has passed, so a
--       future-dated last_attempt_at would park an event indefinitely. It
--       cannot be exactly now(): a later mark-published keeps the earlier
--       failed attempt's time.
--     - outbox_event_relay_delete, FOR DELETE: past retention only.
--     - SELECT; UPDATE on (published_at, attempts, last_attempt_at, dead_at)
--       only; DELETE. No INSERT (it cannot forge an event), no TRUNCATE, and
--       nothing on any other relation, sequence or function.
--   The retention windows (7 and 30 days, D-L128 Q3) live in these policies
--   AND in sweepOutbox's DELETE (@kasuwa/db outbox-relay.ts): change both.
--
--   kasuwa_auth, kasuwa_sweeper, PUBLIC: nothing (REVOKE ALL, belt and
--   braces: the bootstrap's default privileges name only kasuwa_app).
--   kasuwa_test_admin: full DML, as for every table (inert outside
--   development and test, packages/db/CLAUDE.md invariant 10).
--   Owned by kasuwa_migrator.
--
-- ---------------------------------------------------------------------------
-- INDEXES
-- ---------------------------------------------------------------------------
--   - outbox_event_pkey (id): the consumer's re-read and the relay's mark.
--   - outbox_event_pending_seq_idx (seq) WHERE undispatched: the claim scan.
--   - outbox_event_pending_aggregate_idx (aggregate_type, aggregate_id, seq)
--     WHERE undispatched: the claim's NOT EXISTS "an earlier event of this
--     aggregate is still pending". An aggregate is (tenant_id, aggregate_type,
--     aggregate_id) everywhere the relay compares them (D-L161), so one
--     tenant's poison row can never hold back another tenant's events. The
--     index keeps the T-0098 suite's pinned key (aggregate_type,
--     aggregate_id, seq) and tenant_id is a filter on it: aggregate ids are
--     uuids, so the extra leading column would buy no selectivity, and
--     D-L161's (tenant_id, ...) key would fail the unmodified suite's
--     catalogue test (I3). Raised in the T-0098 report.
--   - outbox_event_published_idx (published_at) WHERE published_at IS NOT
--     NULL, and outbox_event_dead_idx (dead_at) WHERE dead_at IS NOT NULL:
--     the sweep's two range deletes, so retention never scans the table.
--   - outbox_event_programme_idx (tenant_id, programme_id): the FK lookups a
--     programme or tenant delete makes (0027's M1: without it each deleted
--     parent seq-scans the table).
--   All built on an empty table.
--
-- AUTOVACUUM (D-L161). The table churns: every row is inserted, updated once
-- or more (published, attempts) and deleted within 7 to 30 days, and the
-- claim scans the pending partial indexes every second. Default thresholds
-- (20% dead tuples) would let dead index entries pile up under a big
-- backlog, so the table vacuums at 1% + 1,000 rows and analyzes at 2%.
--
-- ---------------------------------------------------------------------------
-- LOCK IMPACT (D-L65)
-- ---------------------------------------------------------------------------
--   - tenant, programme: SHARE ROW EXCLUSIVE for the whole file, which is
--     what creating an FK that references them takes anyway, taken up front
--     in one order. It blocks writes to those two tables, not reads, for the
--     milliseconds the file takes.
--   - lock_timeout = 5s: refuse to queue behind a long transaction.
--
-- ---------------------------------------------------------------------------
-- EXPAND ONLY
-- ---------------------------------------------------------------------------
-- A new table with no reader in old code. Old API, worker and realtime builds
-- run unchanged against it. The new worker needs DATABASE_RELAY_URL and
-- refuses to boot without it (workerEnv), so deploy order is: bootstrap
-- (creates kasuwa_relay; real cells: with its secrets-manager password first),
-- then this migration, then the worker.
--
-- ---------------------------------------------------------------------------
-- ROLLBACK PLAN
-- ---------------------------------------------------------------------------
-- If this file fails, nothing was applied (one transaction; the runner records
-- it only on COMMIT). Fix the cause (usually: re-apply bootstrap.sql as the
-- superuser) and run `pnpm db:migrate` again.
-- To undo it after it has applied: never edit or delete this file or its
-- ledger row (append-only). Instead:
--   1. roll back the application first (the worker's relay loop and every
--      producer calling appendOutboxEvent), then the schema.ts mirror and the
--      TENANT_SCOPED_TABLES entry;
--   2. in a NEW migration, as kasuwa_migrator: DROP TABLE outbox_event (its
--      policies, indexes, grants and FKs go with it). Undispatched events are
--      lost with it; drain the relay first if they matter;
--   3. kasuwa_relay then holds nothing on any table. To retire the role, as
--      the superuser: REVOKE CONNECT ON DATABASE kasuwa FROM kasuwa_relay;
--      REVOKE USAGE ON SCHEMA public FROM kasuwa_relay; DROP ROLE
--      kasuwa_relay; and remove it from sql/bootstrap.sql in the same change
--      (a lead-owned file), or the next bootstrap run recreates it.
-- ---------------------------------------------------------------------------

SET LOCAL lock_timeout = '5s';

-- --- 1. the role must be what ADR-0018 point 4 says, and hold nothing yet ----
DO $$
DECLARE
  relay pg_catalog.pg_roles%ROWTYPE;
  held text;
BEGIN
  SELECT * INTO relay FROM pg_catalog.pg_roles WHERE rolname = 'kasuwa_relay';
  IF NOT FOUND THEN
    RAISE EXCEPTION
      'kasuwa_relay does not exist: this database was bootstrapped before T-0098. '
      'Re-apply the bootstrap as the superuser, then migrate again. Local dev: '
      '`docker exec -i kasuwa-postgres psql -U postgres -d kasuwa -v ON_ERROR_STOP=1 '
      '< packages/db/sql/bootstrap.sql` (it is idempotent). Real environments: '
      'create kasuwa_relay with its secrets-manager password, then apply the '
      'bootstrap. See packages/db/CLAUDE.md.';
  END IF;
  IF NOT relay.rolcanlogin OR relay.rolbypassrls OR relay.rolsuper
     OR relay.rolcreaterole OR relay.rolcreatedb OR relay.rolreplication THEN
    RAISE EXCEPTION
      'kasuwa_relay must be LOGIN, NOBYPASSRLS, NOSUPERUSER, NOCREATEROLE, NOCREATEDB '
      'and NOREPLICATION (ADR-0018 point 4). Its policies are all that bound it.';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_catalog.pg_auth_members m
              WHERE m.member = relay.oid OR m.roleid = relay.oid) THEN
    RAISE EXCEPTION
      'kasuwa_relay is a member of a role, or a role is a member of it. Either way a '
      'SET ROLE crosses the boundary this role exists to draw (ADR-0018 point 4).';
  END IF;

  -- Owns nothing, and no default privilege names it.
  SELECT pg_catalog.string_agg(x.what, ', ' ORDER BY x.what) INTO held
    FROM (
      SELECT 'owns ' || c.oid::pg_catalog.regclass::text AS what
        FROM pg_catalog.pg_class c WHERE c.relowner = relay.oid
      UNION ALL
      SELECT 'owns ' || p.oid::pg_catalog.regprocedure::text
        FROM pg_catalog.pg_proc p WHERE p.proowner = relay.oid
      UNION ALL
      SELECT 'owns schema ' || n.nspname::text
        FROM pg_catalog.pg_namespace n WHERE n.nspowner = relay.oid
      UNION ALL
      SELECT 'a default privilege'
        FROM pg_catalog.pg_default_acl d
       WHERE d.defaclrole = relay.oid
          OR EXISTS (SELECT 1 FROM pg_catalog.aclexplode(d.defaclacl) a
                      WHERE a.grantee = relay.oid)
    ) AS x;
  IF held IS NOT NULL THEN
    RAISE EXCEPTION 'kasuwa_relay must own nothing and be named by no default privilege: %', held;
  END IF;

  -- Holds nothing on any relation or sequence, by any route (direct, PUBLIC,
  -- column-level). outbox_event does not exist yet, so the plan is "nothing".
  SELECT pg_catalog.string_agg(c.oid::pg_catalog.regclass::text || ':' || p.priv, ', '
                               ORDER BY c.oid::pg_catalog.regclass::text, p.priv)
    INTO held
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
   CROSS JOIN pg_catalog.unnest(ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE',
                                      'REFERENCES', 'TRIGGER']) AS p(priv)
   WHERE c.relkind IN ('r', 'p', 'v', 'm', 'f')
     AND n.nspname NOT IN ('pg_catalog', 'information_schema')
     AND n.nspname NOT LIKE 'pg\_toast%'
     AND CASE WHEN p.priv IN ('SELECT', 'INSERT', 'UPDATE', 'REFERENCES')
              THEN pg_catalog.has_any_column_privilege(relay.oid, c.oid, p.priv)
              ELSE pg_catalog.has_table_privilege(relay.oid, c.oid, p.priv)
         END;
  IF held IS NOT NULL THEN
    RAISE EXCEPTION 'kasuwa_relay holds privileges beyond ADR-0018 point 4: %', held;
  END IF;
  SELECT pg_catalog.string_agg(c.oid::pg_catalog.regclass::text || ':' || p.priv, ', ')
    INTO held
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
   CROSS JOIN pg_catalog.unnest(ARRAY['USAGE', 'SELECT', 'UPDATE']) AS p(priv)
   WHERE c.relkind = 'S'
     AND n.nspname NOT IN ('pg_catalog', 'information_schema')
     AND pg_catalog.has_sequence_privilege(relay.oid, c.oid, p.priv);
  IF held IS NOT NULL THEN
    RAISE EXCEPTION 'kasuwa_relay holds sequence privileges: %', held;
  END IF;

  -- Schemas: USAGE on public alone, CREATE nowhere. Database: CONNECT only.
  SELECT pg_catalog.string_agg(n.nspname::text, ', ' ORDER BY n.nspname) INTO held
    FROM pg_catalog.pg_namespace n
   WHERE n.nspname NOT IN ('pg_catalog', 'information_schema')
     AND n.nspname NOT LIKE 'pg\_%'
     AND ((n.nspname <> 'public' AND pg_catalog.has_schema_privilege(relay.oid, n.oid, 'USAGE'))
          OR pg_catalog.has_schema_privilege(relay.oid, n.oid, 'CREATE'));
  IF held IS NOT NULL THEN
    RAISE EXCEPTION 'kasuwa_relay may use or create in schema(s) beyond USAGE on public: %', held;
  END IF;
  IF NOT pg_catalog.has_schema_privilege(relay.oid, 'public', 'USAGE')
     OR NOT pg_catalog.has_database_privilege(relay.oid, pg_catalog.current_database(), 'CONNECT') THEN
    RAISE EXCEPTION 'kasuwa_relay lacks CONNECT on the database or USAGE on public: re-apply bootstrap.sql';
  END IF;
  IF pg_catalog.has_database_privilege(relay.oid, pg_catalog.current_database(), 'CREATE')
     OR pg_catalog.has_database_privilege(relay.oid, pg_catalog.current_database(), 'TEMPORARY') THEN
    RAISE EXCEPTION 'kasuwa_relay may CREATE or TEMPORARY on the database (ADR-0018 point 4)';
  END IF;

  -- No function grant names it, and it can execute neither SECURITY DEFINER.
  SELECT pg_catalog.string_agg(p.oid::pg_catalog.regprocedure::text, ', ') INTO held
    FROM pg_catalog.pg_proc p
   WHERE (p.proacl IS NOT NULL
          AND EXISTS (SELECT 1 FROM pg_catalog.aclexplode(p.proacl) a WHERE a.grantee = relay.oid))
      OR (p.prosecdef
          AND p.pronamespace NOT IN ('pg_catalog'::pg_catalog.regnamespace,
                                     'information_schema'::pg_catalog.regnamespace)
          AND pg_catalog.has_function_privilege(relay.oid, p.oid, 'EXECUTE'));
  IF held IS NOT NULL THEN
    RAISE EXCEPTION 'kasuwa_relay is granted or can execute function(s) it must not: %', held;
  END IF;
END
$$;

-- --- 2. locks, in a fixed order ----------------------------------------------
LOCK TABLE tenant, programme IN SHARE ROW EXCLUSIVE MODE;

-- --- 3. the table ----------------------------------------------------------------
CREATE TABLE outbox_event (
  id               uuid        PRIMARY KEY,
  seq              bigint      GENERATED ALWAYS AS IDENTITY,
  tenant_id        uuid        NOT NULL,
  programme_id     uuid        NOT NULL,
  actor_user_id    uuid        NOT NULL,
  event_type       text        NOT NULL,
  schema_version   smallint    NOT NULL DEFAULT 1,
  aggregate_type   text        NOT NULL,
  aggregate_id     uuid        NOT NULL,
  payload          jsonb       NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  published_at     timestamptz,
  attempts         smallint    NOT NULL DEFAULT 0,
  last_attempt_at  timestamptz,
  dead_at          timestamptz,

  CONSTRAINT outbox_event_tenant_fk
    FOREIGN KEY (tenant_id)
    REFERENCES tenant (id) ON DELETE CASCADE ON UPDATE RESTRICT,
  CONSTRAINT outbox_event_programme_same_tenant_fk
    FOREIGN KEY (tenant_id, programme_id)
    REFERENCES programme (tenant_id, id) ON DELETE CASCADE ON UPDATE RESTRICT,

  -- Codes, never text a person wrote: they reach logs and metric labels.
  CONSTRAINT outbox_event_event_type_check
    CHECK (char_length(event_type) <= 100
           AND event_type ~ '^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$'),
  CONSTRAINT outbox_event_aggregate_type_check
    CHECK (aggregate_type ~ '^[a-z][a-z0-9_]{0,62}$'),
  CONSTRAINT outbox_event_schema_version_check CHECK (schema_version >= 1),
  -- An object of identifiers. 8 KiB is far above any registered schema.
  CONSTRAINT outbox_event_payload_check
    CHECK (jsonb_typeof(payload) = 'object' AND octet_length(payload::text) <= 8192),
  CONSTRAINT outbox_event_attempts_check CHECK (attempts >= 0),
  -- Published or dead, never both.
  CONSTRAINT outbox_event_settled_once_check
    CHECK (published_at IS NULL OR dead_at IS NULL)
);

CREATE INDEX outbox_event_pending_seq_idx
  ON outbox_event (seq)
  WHERE published_at IS NULL AND dead_at IS NULL;
CREATE INDEX outbox_event_pending_aggregate_idx
  ON outbox_event (aggregate_type, aggregate_id, seq)
  WHERE published_at IS NULL AND dead_at IS NULL;
CREATE INDEX outbox_event_published_idx
  ON outbox_event (published_at)
  WHERE published_at IS NOT NULL;
CREATE INDEX outbox_event_dead_idx
  ON outbox_event (dead_at)
  WHERE dead_at IS NOT NULL;
CREATE INDEX outbox_event_programme_idx
  ON outbox_event (tenant_id, programme_id);

-- See AUTOVACUUM in the header.
ALTER TABLE outbox_event SET (
  autovacuum_vacuum_scale_factor = 0.01,
  autovacuum_vacuum_threshold = 1000,
  autovacuum_analyze_scale_factor = 0.02
);

-- --- 4. RLS and policies -----------------------------------------------------------
ALTER TABLE outbox_event ENABLE ROW LEVEL SECURITY;
ALTER TABLE outbox_event FORCE ROW LEVEL SECURITY;

CREATE POLICY outbox_event_tenant ON outbox_event FOR ALL TO kasuwa_app
  USING      (tenant_id = app.current_tenant_id()
              AND programme_id = ANY (app.current_programme_ids()))
  WITH CHECK (tenant_id = app.current_tenant_id()
              AND programme_id = ANY (app.current_programme_ids()));

-- F-R3 (D-L156). RESTRICTIVE: AND-ed with outbox_event_tenant on INSERT.
CREATE POLICY outbox_event_insert_as_session ON outbox_event AS RESTRICTIVE
  FOR INSERT TO kasuwa_app
  WITH CHECK (actor_user_id = app.current_user_id());

-- The relay's three. The retention windows are repeated in sweepOutbox.
CREATE POLICY outbox_event_relay_select ON outbox_event FOR SELECT TO kasuwa_relay
  USING ((published_at IS NULL AND dead_at IS NULL)
         OR published_at = now()
         OR dead_at = now()
         OR published_at < now() - interval '7 days'
         OR dead_at < now() - interval '30 days');

CREATE POLICY outbox_event_relay_update ON outbox_event FOR UPDATE TO kasuwa_relay
  USING      (published_at IS NULL AND dead_at IS NULL)
  WITH CHECK ((published_at IS NULL OR published_at = now())
              AND (dead_at IS NULL OR dead_at = now())
              AND (last_attempt_at IS NULL OR last_attempt_at <= now()));

CREATE POLICY outbox_event_relay_delete ON outbox_event FOR DELETE TO kasuwa_relay
  USING (published_at < now() - interval '7 days'
         OR dead_at < now() - interval '30 days');

-- --- 5. grants ------------------------------------------------------------------------
-- Explicit, so this file does not silently depend on the bootstrap's default
-- privileges (which would give kasuwa_app UPDATE and DELETE).
REVOKE ALL ON outbox_event
  FROM PUBLIC, kasuwa_app, kasuwa_auth, kasuwa_sweeper, kasuwa_relay, kasuwa_test_admin;
GRANT SELECT ON outbox_event TO kasuwa_app;
GRANT INSERT (id, tenant_id, programme_id, actor_user_id, event_type, schema_version,
              aggregate_type, aggregate_id, payload)
  ON outbox_event TO kasuwa_app;

GRANT SELECT, DELETE ON outbox_event TO kasuwa_relay;
GRANT UPDATE (published_at, attempts, last_attempt_at, dead_at) ON outbox_event TO kasuwa_relay;

GRANT SELECT, INSERT, UPDATE, DELETE ON outbox_event TO kasuwa_test_admin;

-- The identity sequence. GENERATED ALWAYS draws from it without a privilege
-- check, so nobody needs a grant; the default privileges gave kasuwa_app
-- USAGE and SELECT, which are taken back.
DO $$
DECLARE
  sequence_name text := pg_catalog.pg_get_serial_sequence('public.outbox_event', 'seq');
BEGIN
  IF sequence_name IS NULL THEN
    RAISE EXCEPTION '0041: outbox_event.seq has no identity sequence';
  END IF;
  EXECUTE pg_catalog.format(
    'REVOKE ALL ON SEQUENCE %s FROM PUBLIC, kasuwa_app, kasuwa_auth, kasuwa_sweeper, kasuwa_relay',
    sequence_name);
END
$$;

-- --- 6. prove the posture ------------------------------------------------------------
-- Runs once, here. The standing guards are the T-0098 acceptance suites and
-- rls-enforcement, which run on every build.
DO $$
DECLARE
  app_role constant pg_catalog.oid := 'kasuwa_app'::pg_catalog.regrole;
  relay constant pg_catalog.oid := 'kasuwa_relay'::pg_catalog.regrole;
  outbox constant pg_catalog.oid := 'public.outbox_event'::pg_catalog.regclass;
  held text;
BEGIN
  IF NOT (SELECT c.relrowsecurity AND c.relforcerowsecurity
            FROM pg_catalog.pg_class c WHERE c.oid = outbox) THEN
    RAISE EXCEPTION '0041: outbox_event RLS is not enabled and forced';
  END IF;
  IF pg_catalog.pg_get_userbyid((SELECT c.relowner FROM pg_catalog.pg_class c WHERE c.oid = outbox))
     <> 'kasuwa_migrator' THEN
    RAISE EXCEPTION '0041: outbox_event is not owned by kasuwa_migrator';
  END IF;

  -- kasuwa_app: SELECT and column-limited INSERT; no UPDATE, DELETE,
  -- TRUNCATE, REFERENCES, TRIGGER; no INSERT on seq or the publication columns.
  IF NOT (pg_catalog.has_table_privilege(app_role, outbox, 'SELECT')
          AND pg_catalog.has_column_privilege(app_role, outbox, 'payload', 'INSERT')) THEN
    RAISE EXCEPTION '0041: kasuwa_app cannot read and append outbox events';
  END IF;
  SELECT pg_catalog.string_agg(x.what, ', ' ORDER BY x.what) INTO held
    FROM (
      SELECT 'UPDATE' AS what WHERE pg_catalog.has_any_column_privilege(app_role, outbox, 'UPDATE')
      UNION ALL SELECT 'DELETE' WHERE pg_catalog.has_table_privilege(app_role, outbox, 'DELETE')
      UNION ALL SELECT 'TRUNCATE' WHERE pg_catalog.has_table_privilege(app_role, outbox, 'TRUNCATE')
      UNION ALL SELECT 'REFERENCES'
                 WHERE pg_catalog.has_any_column_privilege(app_role, outbox, 'REFERENCES')
      UNION ALL SELECT 'TRIGGER' WHERE pg_catalog.has_table_privilege(app_role, outbox, 'TRIGGER')
      UNION ALL SELECT 'INSERT ' || c.col
                  FROM pg_catalog.unnest(ARRAY['seq', 'created_at', 'published_at', 'attempts',
                                               'last_attempt_at', 'dead_at']) AS c(col)
                 WHERE pg_catalog.has_column_privilege(app_role, outbox, c.col, 'INSERT')
    ) AS x;
  IF held IS NOT NULL THEN
    RAISE EXCEPTION '0041: kasuwa_app holds what it must not on outbox_event: %', held;
  END IF;

  -- kasuwa_relay: exactly SELECT, DELETE, and UPDATE on four columns, on
  -- outbox_event; nothing on any other relation (asserted before section 2).
  SELECT pg_catalog.string_agg(x.what, ', ' ORDER BY x.what) INTO held
    FROM (
      SELECT 'missing SELECT' AS what WHERE NOT pg_catalog.has_table_privilege(relay, outbox, 'SELECT')
      UNION ALL SELECT 'missing DELETE' WHERE NOT pg_catalog.has_table_privilege(relay, outbox, 'DELETE')
      UNION ALL SELECT 'INSERT' WHERE pg_catalog.has_any_column_privilege(relay, outbox, 'INSERT')
      UNION ALL SELECT 'TRUNCATE' WHERE pg_catalog.has_table_privilege(relay, outbox, 'TRUNCATE')
      UNION ALL SELECT 'REFERENCES' WHERE pg_catalog.has_any_column_privilege(relay, outbox, 'REFERENCES')
      UNION ALL SELECT 'TRIGGER' WHERE pg_catalog.has_table_privilege(relay, outbox, 'TRIGGER')
      UNION ALL SELECT CASE WHEN pg_catalog.has_column_privilege(relay, outbox, a.attname, 'UPDATE')
                            THEN 'UPDATE ' || a.attname ELSE 'missing UPDATE ' || a.attname END
                  FROM pg_catalog.pg_attribute a
                 WHERE a.attrelid = outbox AND a.attnum > 0 AND NOT a.attisdropped
                   AND pg_catalog.has_column_privilege(relay, outbox, a.attname, 'UPDATE')
                       <> (a.attname IN ('published_at', 'attempts', 'last_attempt_at', 'dead_at'))
    ) AS x;
  IF held IS NOT NULL THEN
    RAISE EXCEPTION '0041: kasuwa_relay privileges on outbox_event are not ADR-0018 point 4: %', held;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_catalog.pg_class c
              WHERE c.relkind = 'S'
                AND c.relnamespace = 'public'::pg_catalog.regnamespace
                AND (pg_catalog.has_sequence_privilege(relay, c.oid, 'USAGE')
                     OR pg_catalog.has_sequence_privilege(relay, c.oid, 'SELECT')
                     OR pg_catalog.has_sequence_privilege(relay, c.oid, 'UPDATE'))) THEN
    RAISE EXCEPTION '0041: kasuwa_relay holds a sequence privilege';
  END IF;

  -- Policies: one permissive TO kasuwa_app with WITH CHECK = USING; the
  -- relay's SELECT, UPDATE and DELETE; restrictive ones TO kasuwa_app only.
  IF (SELECT pg_catalog.count(*) FROM pg_catalog.pg_policy p
       WHERE p.polrelid = outbox AND p.polpermissive AND p.polroles = ARRAY[app_role]
         AND p.polcmd = '*'
         AND pg_catalog.pg_get_expr(p.polqual, p.polrelid)
             = pg_catalog.pg_get_expr(p.polwithcheck, p.polrelid)) <> 1 THEN
    RAISE EXCEPTION '0041: outbox_event needs one permissive FOR ALL policy TO kasuwa_app with WITH CHECK = USING';
  END IF;
  IF (SELECT pg_catalog.array_agg(p.polcmd::text ORDER BY p.polcmd::text)
        FROM pg_catalog.pg_policy p
       WHERE p.polrelid = outbox AND p.polroles = ARRAY[relay]) IS DISTINCT FROM ARRAY['d', 'r', 'w'] THEN
    RAISE EXCEPTION '0041: kasuwa_relay must have exactly its SELECT, UPDATE and DELETE policies';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_catalog.pg_policy p
              WHERE p.polrelid = outbox
                AND p.polroles <> ARRAY[app_role] AND p.polroles <> ARRAY[relay]) THEN
    RAISE EXCEPTION '0041: an outbox_event policy names a role other than kasuwa_app or kasuwa_relay';
  END IF;

  -- PUBLIC, kasuwa_auth and every role kasuwa_app can enter hold nothing.
  SELECT pg_catalog.string_agg(r.rolname || ':' || p.priv, ', ' ORDER BY r.rolname, p.priv)
    INTO held
    FROM pg_catalog.pg_roles r
   CROSS JOIN pg_catalog.unnest(ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE',
                                      'REFERENCES', 'TRIGGER']) AS p(priv)
   WHERE (r.rolname = 'kasuwa_auth'
          OR (r.oid <> app_role AND pg_catalog.pg_has_role(app_role, r.oid, 'MEMBER')))
     AND CASE WHEN p.priv IN ('SELECT', 'INSERT', 'UPDATE', 'REFERENCES')
              THEN pg_catalog.has_any_column_privilege(r.oid, outbox, p.priv)
              ELSE pg_catalog.has_table_privilege(r.oid, outbox, p.priv)
         END;
  IF held IS NOT NULL THEN
    RAISE EXCEPTION '0041: a role other than kasuwa_app and kasuwa_relay holds a privilege on outbox_event: %', held;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_catalog.pg_class c, pg_catalog.aclexplode(c.relacl) a
              WHERE c.oid = outbox AND a.grantee = 0) THEN
    RAISE EXCEPTION '0041: PUBLIC holds a privilege on outbox_event';
  END IF;

  -- The identity sequence: no serving role holds anything on it.
  SELECT pg_catalog.string_agg(r.rolname || ':' || p.priv, ', ' ORDER BY r.rolname, p.priv)
    INTO held
    FROM pg_catalog.pg_roles r
   CROSS JOIN pg_catalog.unnest(ARRAY['USAGE', 'SELECT', 'UPDATE']) AS p(priv)
   WHERE r.rolname IN ('kasuwa_app', 'kasuwa_auth', 'kasuwa_sweeper', 'kasuwa_relay')
     AND pg_catalog.has_sequence_privilege(
           r.oid, pg_catalog.pg_get_serial_sequence('public.outbox_event', 'seq'), p.priv);
  IF held IS NOT NULL THEN
    RAISE EXCEPTION '0041: a serving role holds a privilege on the outbox_event identity sequence: %', held;
  END IF;

  -- CLAUDE.md 2.7: still exactly the two SECURITY DEFINER functions.
  IF (SELECT pg_catalog.count(*) FROM pg_catalog.pg_proc p
       WHERE p.prosecdef
         AND p.pronamespace NOT IN ('pg_catalog'::pg_catalog.regnamespace,
                                    'information_schema'::pg_catalog.regnamespace)) <> 2 THEN
    RAISE EXCEPTION '0041: there must be exactly two SECURITY DEFINER functions (CLAUDE.md 2.7)';
  END IF;
END
$$;
