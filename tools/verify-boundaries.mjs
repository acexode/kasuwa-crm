#!/usr/bin/env node
/**
 * Proves the module-boundary rule is actually enforcing, not merely configured.
 *
 * A lint rule that is present but silently inert is worse than no rule: the
 * whole team stops thinking about boundaries because "the linter has it". So
 * CI writes a file that deliberately violates the constraints, runs ESLint on
 * it, and fails if ESLint is happy.
 *
 * The probe: packages/domain/core (scope:domain) importing @kasuwa/testing
 * (type:testing). Domain modules may depend only on scope:shared and
 * scope:adapter, so this must be reported.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const probePath = resolve(root, 'packages/domain/core/src/__boundary_probe__.ts');

// Two probes. The first violates a TAG constraint only, so nothing but the Nx
// rule can catch it - that is what makes this check meaningful. The second is
// also covered by no-restricted-imports, and is here so a regression in either
// rule is distinguishable in the output.
const PROBE_SOURCE = `// Generated by tools/verify-boundaries.mjs. Deleted immediately after linting.
import { AppModule } from '@kasuwa/api';
import { withForcedScope } from '@kasuwa/testing';

export const probe = [AppModule, withForcedScope];
`;

function cleanup() {
  if (existsSync(probePath)) {
    rmSync(probePath);
  }
}

function main() {
  cleanup();
  writeFileSync(probePath, PROBE_SOURCE, 'utf8');

  const result = spawnSync(
    'npx',
    ['eslint', '--no-ignore', '--format', 'json', 'packages/domain/core/src/__boundary_probe__.ts'],
    { cwd: root, encoding: 'utf8', shell: process.platform === 'win32' },
  );

  cleanup();

  let reports;
  try {
    reports = JSON.parse(result.stdout || '[]');
  } catch {
    console.error('could not parse eslint output:');
    console.error(result.stdout);
    console.error(result.stderr);
    process.exit(1);
  }

  const messages = reports.flatMap((report) => report.messages ?? []);
  const ruleIds = new Set(messages.map((message) => message.ruleId));

  const boundaryReported = ruleIds.has('@nx/enforce-module-boundaries');
  const importReported = ruleIds.has('no-restricted-imports');

  if (!boundaryReported && !importReported) {
    console.error(
      'BOUNDARY CHECK FAILED: a domain package importing @kasuwa/testing produced no lint error.\n' +
        'Either the Nx project graph is not resolving tags, or the rule is misconfigured.\n' +
        `Rules that did fire: ${[...ruleIds].join(', ') || '(none)'}`,
    );
    process.exit(1);
  }

  console.log(
    'boundary enforcement verified ' +
      `(@nx/enforce-module-boundaries: ${boundaryReported}, no-restricted-imports: ${importReported})`,
  );
}

try {
  main();
} catch (error) {
  cleanup();
  console.error(error.message);
  process.exit(1);
}
