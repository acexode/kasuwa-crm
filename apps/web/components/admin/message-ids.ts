/**
 * Which strings each P02 screen needs, resolved on the SERVER.
 *
 * Same rule as `components/auth/message-ids.ts`, and for the same two reasons.
 *
 * **No `'use client'` in this file, ever.** A client module's exports become
 * client references, so a server component importing one gets a proxy object
 * instead of an array — which fails at request time with "ids is not iterable"
 * rather than at compile time. It cost a full e2e run to find on P01.
 *
 * **Bandwidth.** `createTranslator` closes over every registered catalogue;
 * shipping nine of them to render one screen is most of what a user on 256 kbps
 * waits for. The server resolves what a screen asks for and only that crosses
 * the wire.
 */

