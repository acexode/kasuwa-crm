  describe('3. smoke: the API signs in with its auth pool on kasuwa_auth', () => {
    let app: INestApplication | undefined;
    let watcher: Client;
    const backendsBefore = new Set<number>();

    beforeAll(async () => {
      await reseed(inject('migrationUrl'));
      await resetSeededTotpUsage(inject('migrationUrl'));
      // One connection, opened BEFORE the API, so every backend that appears
      // after the snapshot belongs to the API.
      watcher = new Client({ connectionString: inject('testAdminUrl') });
      await watcher.connect();
      const before = await watcher.query<{ pid: number }>(
        'SELECT pid FROM pg_stat_activity WHERE datname = current_database()',
      );
      for (const row of before.rows) backendsBefore.add(row.pid);
    });

    afterAll(async () => {
      await app?.close();
      await watcher?.end();
      await reseed(inject('migrationUrl'));
    });

    it('signs in (password + TOTP), serves /me, signs out — and the auth writes came from a kasuwa_auth backend', async () => {
      // Built as a variable, so the new option typechecks on main (I5). Booted
      // inside the test, so a missing harness value fails it rather than skips.
      const options: AppModuleOptions & { authDatabaseUrl: string } = {
        databaseUrl: inject('databaseUrl'),
        authDatabaseUrl: authDatabaseUrl(),
        poolMax: 2,
      };
      const moduleRef = await Test.createTestingModule({
        imports: [AppModule.forRoot(options)],
      }).compile();
      app = moduleRef.createNestApplication({ logger: false });
      await app.init();
      const server = app.getHttpServer();
      const credentials = seededCredentials(USER_A_SUPERVISOR);

      const started = await request(server)
        .post('/api/v1/auth/sign-in')
        .send({
          tenantSlug: credentials.tenantSlug,
          email: credentials.email,
          password: credentials.password,
        })
        .expect(200);
      const verified = await request(server)
        .post('/api/v1/auth/mfa')
        .send({
          challengeId: started.body.challengeId,
          code: freshSeededTotpCode(USER_A_SUPERVISOR),
        })
        .expect(200);
      const token = verified.body.accessToken as string;
      expect(token).toEqual(expect.any(String));

      await request(server)
        .get('/api/v1/auth/me')
        .set('Authorization', `Bearer ${token}`)
        .expect(200);

      // While the pools' connections are still open (pg keeps them idle for
      // ten seconds): which roles did the API connect as?
      const after = await watcher.query<{ pid: number; usename: string }>(
        `SELECT pid, usename FROM pg_stat_activity
          WHERE datname = current_database()
            AND pid <> pg_backend_pid()
            AND application_name IS DISTINCT FROM $1`,
        [SUITE_APP_NAME],
      );
      const apiRoles = new Set(
        after.rows.filter((row) => !backendsBefore.has(row.pid)).map((row) => row.usename),
      );
      expect([...apiRoles].sort(), 'the API connected as these roles').toEqual([
        'kasuwa_app',
        'kasuwa_auth',
      ]);

      await request(server)
        .post('/api/v1/auth/sign-out')
        .set('Authorization', `Bearer ${token}`)
        .expect(204);
      await request(server)
        .get('/api/v1/auth/me')
        .set('Authorization', `Bearer ${token}`)
        .expect(401);
    });
  });
