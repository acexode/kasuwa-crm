interface RecordingQueue {
  queues: Record<string, OutboxQueue>;
  /** Every job, in enqueue order, with the queue it went to. */
  jobs: (OutboxJob & { queue: string })[];
}

/** A stand-in for BullMQ that records what it is given. */
function recordingQueues(
  onAdd?: (jobs: readonly OutboxJob[]) => Promise<void>,
): RecordingQueue {
  const recorded: RecordingQueue = { queues: {}, jobs: [] };
  recorded.queues[NOTIFICATIONS_QUEUE] = {
    addBulk: async (jobs) => {
      recorded.jobs.push(...jobs.map((job) => ({ ...job, queue: NOTIFICATIONS_QUEUE })));
      if (onAdd !== undefined) await onAdd(jobs);
      return jobs;
    },
  };
  return recorded;
}

function failingQueues(): RecordingQueue {
  const recorded: RecordingQueue = { queues: {}, jobs: [] };
  recorded.queues[NOTIFICATIONS_QUEUE] = {
    addBulk: async (jobs) => {
      recorded.jobs.push(...jobs.map((job) => ({ ...job, queue: NOTIFICATIONS_QUEUE })));
      throw new Error('queue unavailable');
    },
  };
  return recorded;
}

function jobIds(recorded: RecordingQueue): string[] {
  return recorded.jobs.map((job) => String(job.opts?.jobId));
}

function keepsCompletedForAWeek(value: unknown): boolean {
  // Unset or false: BullMQ keeps every completed job, which satisfies Q3.
  if (value === undefined || value === false) return true;
  if (typeof value === 'object' && value !== null) {
    const keep = value as Record<string, unknown>;
    return typeof keep.age === 'number' && keep.age >= WEEK_SECONDS && keep.count === undefined;
  }
  // true (remove at once) or a number (keep the last N) can drop a job inside
  // the published-row window, and then BullMQ no longer dedupes its jobId.
  return false;
}

