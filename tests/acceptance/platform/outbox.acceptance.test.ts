function sqlState(error: unknown): string {
  const code = (error as { code?: unknown }).code;
  return typeof code === 'string' ? code : `non-sql error: ${String(error)}`;
}

async function settle(promise: Promise<unknown>): Promise<{ ok: true } | { error: unknown }> {
  try {
    await promise;
    return { ok: true };
  } catch (error) {
    return { error };
  }
}

function deferred(): { promise: Promise<void>; resolve: () => void } {
  let release: () => void = () => undefined;
  const promise = new Promise<void>((done) => {
    release = done;
  });
  return { promise, resolve: () => release() };
}

/** The nth seeded contact in a programme. Ids only ever leave this function. */
function seededContact(tenantId: string, programmeId: string, nth = 0): string {
  const found = SEED_CONTACTS.filter(
    (contact) => contact.tenantId === tenantId && contact.programmeId === programmeId,
  )[nth];
  if (found === undefined) {
    throw new Error(`fixture: no seeded contact #${nth} in programme ${programmeId}`);
  }
  return found.id;
}

